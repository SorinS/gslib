// isprintMode writes the ranges of non-ASCII runes that strconv.IsPrint
// accepts, which strconv.Quote (Go's %q) writes as they are.
func isprintMode(args []string) error {
	fs := flag.NewFlagSet("isprint", flag.ExitOnError)
	fs.Parse(args)
	if fs.NArg() != 0 {
		fs.Usage()
		os.Exit(2)
	}
	var ranges [][2]rune
	for r := rune(0x80); r <= utf8.MaxRune; r++ {
		if !strconv.IsPrint(r) {
			continue
		}
		if n := len(ranges); n > 0 && ranges[n-1][1] == r-1 {
			ranges[n-1][1] = r
		} else {
			ranges = append(ranges, [2]rune{r, r})
		}
	}
	w := bufio.NewWriter(os.Stdout)
	fmt.Fprintf(w, "// mime.isprint: the runes past ASCII that Go's strconv.IsPrint accepts, as\n")
	fmt.Fprintf(w, "// %d ranges [lo, hi]. Generated by `tools/mimeoracle.sh isprint` from %s;\n", len(ranges), runtime.Version())
	fmt.Fprintf(w, "// do not edit.\n\nnamespace mime;\n\n")
	fmt.Fprintf(w, "let PRINT_RANGES: u32[%d] = [\n", 2*len(ranges))
	for i, r := range ranges {
		if i%4 == 0 {
			fmt.Fprint(w, "   ")
		}
		fmt.Fprintf(w, " 0x%x, 0x%x,", r[0], r[1])
		if i%4 == 3 || i == len(ranges)-1 {
			fmt.Fprintln(w)
		}
	}
	fmt.Fprintf(w, "];\n\n")
	fmt.Fprintf(w, `// strconv.IsPrint, for a rune past ASCII.
fn is_print(r: i64) -> bool {
    if r < 0x80 { return r >= 0x20 && r < 0x7F; }
    var lo = 0;
    var hi = PRINT_RANGES.len / 2;
    while lo < hi {
        let mid = (lo + hi) / 2;
        if PRINT_RANGES[2 * mid + 1] < r { lo = mid + 1; } else { hi = mid; }
    }
    return lo < PRINT_RANGES.len / 2 && PRINT_RANGES[2 * lo] <= r;
}
`)
	return w.Flush()
}

// typesMode writes Go's built-in table of extensions, read from
// mime/type.go's builtinTypesLower.
func typesMode(args []string) error {
	fs := flag.NewFlagSet("types", flag.ExitOnError)
	goroot := gorootFlag(fs)
	fs.Parse(args)
	if fs.NArg() != 0 {
		fs.Usage()
		os.Exit(2)
	}
	path := filepath.Join(*goroot, "src", "mime", "type.go")
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		return err
	}
	table := map[string]string{}
	found := false
	ast.Inspect(f, func(n ast.Node) bool {
		vs, ok := n.(*ast.ValueSpec)
		if !ok || len(vs.Names) != 1 || vs.Names[0].Name != "builtinTypesLower" || len(vs.Values) != 1 {
			return true
		}
		lit, ok := vs.Values[0].(*ast.CompositeLit)
		if !ok {
			return true
		}
		for _, e := range lit.Elts {
			kv := e.(*ast.KeyValueExpr)
			k, err1 := strconv.Unquote(kv.Key.(*ast.BasicLit).Value)
			v, err2 := strconv.Unquote(kv.Value.(*ast.BasicLit).Value)
			if err1 != nil || err2 != nil {
				err = fmt.Errorf("unexpected entry in builtinTypesLower")
				return false
			}
			table[k] = v
		}
		found = true
		return false
	})
	if err != nil {
		return err
	}
	if !found {
		return fmt.Errorf("%s: no builtinTypesLower", path)
	}
	keys := make([]string, 0, len(table))
	for k := range table {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	w := bufio.NewWriter(os.Stdout)
	fmt.Fprintf(w, "// mime.types_builtin: Go's built-in table of file extensions (mime/type.go's\n")
	fmt.Fprintf(w, "// builtinTypesLower), %d entries. Generated by `tools/mimeoracle.sh types`\n", len(keys))
	fmt.Fprintf(w, "// from %s; do not edit.\n\nnamespace mime;\n\nimport mime;\n\n", runtime.Version())
	fmt.Fprintf(w, "let BUILTIN_TYPES: KV[%d] = [\n", len(keys))
	for _, k := range keys {
		fmt.Fprintf(w, "    KV { key: %s, value: %s },\n", gooseString(k), gooseString(table[k]))
	}
	fmt.Fprintf(w, "];\n")
	return w.Flush()
}

// gooseString is s as a Goose string literal.
func gooseString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c >= 0x20 && c < 0x7f:
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "\\x%02x", c)
		}
	}
	b.WriteByte('"')
	return b.String()
}
