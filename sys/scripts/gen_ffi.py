#!/usr/bin/env python3
"""Generates sys's FFI from one table, sys/src/api.def, as Go's mksyscall
does for x/sys:

  - sys/ffi.goose        the extern fn declarations and the structs they fill
  - sys/src/gssys_api.h  the C prototypes and the C mirrors of those structs
  - sys/src/gssys_stubs.c, for each function, a body returning
                         GSSYS_ENOTSUP on the platforms it is not for

Every function must exist on every platform (the JIT's library for a
package resolves every extern of its modules), so a Windows call has a stub on
POSIX and the other way round; the C that implements a function wraps it in
the same platform condition, and the compiler checks both against the one
prototype.

    python3 sys/scripts/gen_ffi.py [--check]

--check exits 1 if a generated file differs from what is on disk.

The table, one declaration a line ('#' starts a comment):

    struct Name: field field ...              every field an i64
    TAG ret name(param: type, ...)           a C function gssys_<name>

TAG is the platforms the function is for (all, win, posix, linux, apple,
bsd); ret is i64 or i32. Parameter types: i32, i64, u64, f64, const u8[:],
u8[:], i64[:], f64[:], u8[>..]& (a builder C appends to) and Name& (a
struct of the table, filled by C).
"""

import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
API = os.path.join(ROOT, "src", "api.def")

CONDS = {
    "all": None,
    "win": "defined(_WIN32)",
    "posix": "!defined(_WIN32)",
    "linux": "defined(__linux__)",
    "apple": "defined(__APPLE__)",
    "bsd": "(defined(__APPLE__) || defined(__FreeBSD__) || defined(__OpenBSD__) || defined(__NetBSD__) || defined(__DragonFly__))",
}

SCALARS = {"i32": "int32_t", "i64": "int64_t", "u64": "uint64_t", "f64": "double"}
SLICES = {
    "const u8[:]": "gssys_slice",
    "u8[:]": "gssys_buf",
    "i64[:]": "gssys_i64s",
    "f64[:]": "gssys_f64s",
    "u8[>..]&": "gs_rref",
}


def parse(text):
    structs, fns = [], []
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        m = re.fullmatch(r"struct\s+(\w+)\s*:\s*(.*)", line)
        if m:
            structs.append((m.group(1), m.group(2).split()))
            continue
        m = re.fullmatch(r"(\w+)\s+(i32|i64)\s+(\w+)\((.*)\)", line)
        if not m or m.group(1) not in CONDS:
            sys.exit(f"api.def:{n}: cannot read: {raw}")
        params = []
        for p in filter(None, (s.strip() for s in m.group(4).split(","))):
            pm = re.fullmatch(r"(\w+)\s*:\s*(.+)", p)
            if not pm:
                sys.exit(f"api.def:{n}: bad parameter: {p}")
            params.append((pm.group(1), pm.group(2).strip()))
        fns.append((m.group(1), m.group(2), m.group(3), params, n))
    names = {s for s, _ in structs}
    for tag, ret, name, params, n in fns:
        for pname, ty in params:
            if ty in SCALARS or ty in SLICES:
                continue
            if ty.endswith("&") and ty[:-1] in names:
                continue
            sys.exit(f"api.def:{n}: {name}: unknown type {ty}")
    return structs, fns


def c_type(ty):
    if ty in SCALARS:
        return SCALARS[ty]
    if ty in SLICES:
        return SLICES[ty]
    return f"gssys_{ty[:-1]} *"


def c_proto(ret, name, params):
    ps = ", ".join(f"{c_type(t)}{'' if c_type(t).endswith('*') else ' '}{p}" for p, t in params) or "void"
    return f"{SCALARS[ret]} gssys_{name}({ps})"


def goose_decl(ret, name, params):
    ps = ", ".join(f"{p}: {t}" for p, t in params)
    return f'extern fn {name}({ps}) -> {ret} = "gssys_{name}";'


HEADER = "/* Generated by sys's scripts/gen_ffi.py from src/api.def: do not edit. */\n"


def gen(structs, fns):
    g = ["// Generated by sys's scripts/gen_ffi.py from src/api.def: do not edit.",
         "// sys's C functions, as the C has them; sys.goose and its modules wrap",
         "// them. Results >= 0 are successes, < 0 an error (see sys::error_text).",
         "", "namespace sys;", ""]
    for s, fields in structs:
        g.append(f"struct {s} {{ {', '.join(f + ': i64' for f in fields)} }}")
    g.append("")
    for tag, ret, name, params, _ in fns:
        g.append(goose_decl(ret, name, params) + ("" if tag == "all" else f"    // {tag}"))
    goose = "\n".join(g) + "\n"

    h = [HEADER, "#ifndef GSSYS_API_H", "#define GSSYS_API_H", "",
         "#include <stdint.h>", '#include "goose.h"', "",
         "typedef struct { const uint8_t *data; int64_t len; } gssys_slice;",
         "typedef struct { uint8_t *data; int64_t len; } gssys_buf;",
         "typedef struct { int64_t *data; int64_t len; } gssys_i64s;",
         "typedef struct { double *data; int64_t len; } gssys_f64s;", "",
         "/* A function not for this platform. */",
         "#define GSSYS_ENOTSUP (-1000000)", ""]
    for s, fields in structs:
        h.append(f"typedef struct {{ {' '.join('int64_t ' + f + ';' for f in fields)} }} gssys_{s};")
    h.append("")
    for tag, ret, name, params, _ in fns:
        h.append(c_proto(ret, name, params) + ";")
    h += ["", "#endif"]
    header = "\n".join(h) + "\n"

    c = [HEADER, "/* Each function on the platforms it is not for: GSSYS_ENOTSUP. */", "",
         '#include "gssys_api.h"', ""]
    by_tag = {}
    for f in fns:
        by_tag.setdefault(f[0], []).append(f)
    for tag, group in by_tag.items():
        if CONDS[tag] is None:
            continue
        c.append(f"#if !({CONDS[tag]})")
        for _, ret, name, params, _ in group:
            unused = " ".join(f"(void){p};" for p, _ in params)
            c.append(f"{c_proto(ret, name, params)} {{ {unused + ' ' if unused else ''}return GSSYS_ENOTSUP; }}")
        c.append("#endif")
        c.append("")
    # A translation unit may not be empty.
    c.append("int gssys_stubs_unit;")
    stubs = "\n".join(c) + "\n"
    return {
        os.path.join(ROOT, "ffi.goose"): goose,
        os.path.join(ROOT, "src", "gssys_api.h"): header,
        os.path.join(ROOT, "src", "gssys_stubs.c"): stubs,
    }


def main():
    check = "--check" in sys.argv[1:]
    with open(API) as f:
        out = gen(*parse(f.read()))
    stale = []
    for path, text in out.items():
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            stale.append(path)
            if not check:
                with open(path, "w", newline="\n") as f:
                    f.write(text)
    if check and stale:
        sys.exit("out of date: " + ", ".join(os.path.relpath(p, ROOT) for p in stale))
    if not check:
        print("\n".join(f"wrote {os.path.relpath(p, ROOT)}" for p in stale) or "up to date")


if __name__ == "__main__":
    main()
